import { z } from 'zod';
import { MAX_NOTE_LENGTH, MAX_PASSWORD_LENGTH, MAX_STATS_DAYS } from './constants.js';
import { passwordLength } from './crypto.js';
import { daysBetween, isRealLocalDate } from './datetime.js';
import { getEventType } from './event-types.js';

/**
 * Request contracts shared by both sides.
 *
 * The API derives its validation from these and the web layer derives its
 * types, so a field cannot drift between them. Note what is absent:
 * `local_date` has no place in any request, because the server computes it
 * from the timestamp and the baby's timezone. Leaving it out of the schema
 * makes sending it impossible rather than merely discouraged (spec 5.3).
 */

const UUID = z.string().uuid();
const LOCAL_DATE = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);

/**
 * A length limit counted in characters rather than UTF-16 units.
 *
 * `.max()` counts units, so a note of six hundred emoji would be refused
 * here while every other layer considers it six hundred characters. A rule
 * that two layers count differently is a rule that eventually disagrees
 * with itself (spec 13.1.1).
 */
function boundedText(max: number, min = 0): z.ZodEffects<z.ZodString, string, string> {
  return z.string().min(min).superRefine((value, ctx) => {
    if ([...value].length > max) {
      ctx.addIssue({
        code: z.ZodIssueCode.too_big,
        type: 'string',
        maximum: max,
        inclusive: true,
        message: 'too long',
      });
    }
  });
}

export const loginRequest = z.object({
  username: z.string().min(1).max(100),
  /**
   * Counted the same way the CLI counts it, so a password that could be set
   * can always be used. `.max()` would count UTF-16 units and refuse a
   * password of two hundred emoji that the CLI happily accepted.
   *
   * Only the upper bound is checked here. The minimum is a policy applied
   * when an account is created; enforcing it at login would lock out every
   * existing account the day the policy is raised, and silently.
   */
  password: z.string().min(1).superRefine((value, ctx) => {
    if (passwordLength(value) > MAX_PASSWORD_LENGTH) {
      ctx.addIssue({
        code: z.ZodIssueCode.too_big,
        type: 'string',
        maximum: MAX_PASSWORD_LENGTH,
        inclusive: true,
        message: 'password too long',
      });
    }
  }),
});

export const createBabyRequest = z.object({
  /**
   * Generated by the client, and doubling as the idempotency key.
   *
   * The same reason an event carries one (spec 3.8): a request whose
   * response was lost gets pressed again, and without an id the second
   * press makes a second baby. Optional, because a baby is made once and
   * a caller that does not care can leave it to the server.
   */
  id: UUID.optional(),
  // User-typed content: any language, stored exactly as given, measured in
  // characters rather than bytes (spec 13.1.1).
  nickname: z.string().min(1).max(50),
  gender: z.enum(['male', 'female', 'other']),
  birthDate: LOCAL_DATE,
  timezone: z.string().min(1).max(64).optional(),
});

/**
 * Timezone is absent on purpose.
 *
 * Changing it would invalidate the stored local_date of every existing
 * event, which is a migration rather than an edit. Leaving the field out of
 * the schema makes that impossible instead of merely discouraged (spec 3.4).
 */
export const updateBabyRequest = createBabyRequest.omit({ id: true, timezone: true }).partial();

/**
 * Tag ids are capped well below the hundred bound parameters a D1 query
 * allows (spec 2.5), so attaching them can stay one statement per tag inside
 * a single batch.
 */
const TAG_IDS = z.array(UUID).max(20);

export const createEventRequest = z.object({
  id: UUID,
  typeId: z.string().min(1).max(50),
  intent: z.enum(['start_timer', 'record']),
  startedAt: z.number().int(),
  endedAt: z.number().int().nullable(),
  value: z.number().int().optional(),
  note: boundedText(MAX_NOTE_LENGTH).optional(),
  metadata: z.record(z.string(), z.string()).optional(),
  tagIds: TAG_IDS.optional(),
});

export const updateEventRequest = z.object({
  version: z.number().int().positive(),
  startedAt: z.number().int().optional(),
  endedAt: z.number().int().nullable().optional(),
  value: z.number().int().optional(),
  note: boundedText(MAX_NOTE_LENGTH).optional(),
  metadata: z.record(z.string(), z.string()).optional(),
  tagIds: TAG_IDS.optional(),
});

export const deleteEventRequest = z.object({ version: z.number().int().positive() });

// User-typed content, so any language and counted in characters (spec 13.1.1).
export const createTagRequest = z.object({ name: boundedText(30, 1) });

/**
 * Renaming one.
 *
 * The same field with the same bounds, and a separate schema all the same:
 * the two requests are free to diverge, and a shared one would make that a
 * breaking change rather than an edit.
 */
export const updateTagRequest = z.object({ name: boundedText(30, 1) });

/**
 * Joining a baby with a code somebody shared.
 *
 * Only bounded here. What the code has to look like is decided after it
 * has been normalised, because the dashes and the capitals a person types
 * are presentation and telling them off for either would be unkind
 * (spec 6.5).
 */
export const joinBabyRequest = z.object({ code: boundedText(100, 1) });

/**
 * The incremental sync cursor (spec 5.4).
 *
 * `since` is a rev the server issued, never a timestamp, and it arrives as a
 * query string, hence the coercion.
 */
export const syncQuery = z.object({
  since: z.coerce.number().int().nonnegative().default(0),
  limit: z.coerce.number().int().positive().max(1000).default(200),
});

/** The page size spec 7.9 sets for the tag page: 50 by default, 200 at most. */
export const TAG_FILTER_DEFAULT_LIMIT = 50;
export const TAG_FILTER_MAX_LIMIT = 200;

/**
 * `GET /babies/:id/events?tags=a,b&from=&to=&sort=&limit=&offset=` (spec 7.9).
 *
 * The presence of `tags` is what makes a request this rather than an
 * incremental sync; the route decides that before parsing.
 *
 * `tags` is any of them (OR), deduplicated, and every one has to be a UUID.
 * The list reaches SQL as **one** bound parameter, a JSON array read back
 * with `json_each`, so its length never touches the hundred-parameter limit
 * (spec 4.2). The cap is there to bound the request, not the statement: a
 * family has a handful of tags, and a hundred is far past any of them.
 *
 * `from` and `to` are optional and closed when given (spec 7.9). Unlike the
 * statistics range there is no width cap: the result is paged, so a wide
 * range costs a longer list rather than a bigger response.
 */
export const tagFilterQuery = z
  .object({
    tags: z
      .string()
      .transform((raw) => [...new Set(raw.split(',').map((t) => t.trim()).filter((t) => t !== ''))])
      .pipe(z.array(UUID).min(1).max(100)),
    from: z.string().refine(isRealLocalDate, { message: 'not a real date' }).optional(),
    to: z.string().refine(isRealLocalDate, { message: 'not a real date' }).optional(),
    sort: z.enum(['recent', 'oldest']).default('recent'),
    limit: z.coerce.number().int().positive().max(TAG_FILTER_MAX_LIMIT).default(TAG_FILTER_DEFAULT_LIMIT),
    offset: z.coerce.number().int().nonnegative().default(0),
  })
  .superRefine((q, ctx) => {
    // Re-checked, because a failed `.refine` above does not stop this one
    // from running on the raw strings (see `statsQuery`).
    if (q.from === undefined || q.to === undefined) return;
    if (!isRealLocalDate(q.from) || !isRealLocalDate(q.to)) return;
    if (q.from > q.to) {
      ctx.addIssue({ code: 'custom', message: 'from is after to', path: ['from'] });
    }
  });

export type TagFilterQuery = z.infer<typeof tagFilterQuery>;

/**
 * `GET /babies/:id/stats?types=a,b&from=&to=`
 *
 * The range is closed at both ends and capped at `MAX_STATS_DAYS`, which is
 * what makes spec 5.6's "at most 366 points" true rather than hoped for.
 *
 * `types` is a comma-separated list, checked against the event type config
 * rather than passed to SQL as it arrives. That is what bounds it: the
 * number of configured types is fixed at build time, so the parameter list
 * cannot grow with anything a client sends (spec 2.5's 100-parameter
 * limit).
 */
const localDate = z.string().refine(isRealLocalDate, { message: 'not a real date' });

export const statsQuery = z
  .object({
    types: z
      .string()
      .transform((raw) => [...new Set(raw.split(',').map((t) => t.trim()).filter((t) => t !== ''))])
      .refine((list) => list.length > 0, { message: 'at least one type' })
      .refine((list) => list.every((id) => getEventType(id) !== undefined), {
        message: 'unknown event type',
      }),
    from: localDate,
    to: localDate,
  })
  .superRefine((q, ctx) => {
    // Nothing here may assume the dates parse.
    //
    // A failed `.refine` above marks the result dirty rather than aborting
    // it, so Zod runs this anyway with the raw strings still in place. The
    // first version of this called `daysBetween` unguarded, and a `from` of
    // "invalid" threw out of `safeParse` instead of returning -- which the
    // route turns into a 500 for what is plainly a bad request.
    //
    // `parseLocalDate` throwing is correct and stays: it says "this is a
    // bug", and the bug was calling it with something unvalidated.
    if (!isRealLocalDate(q.from) || !isRealLocalDate(q.to)) return;

    if (q.from > q.to) {
      ctx.addIssue({ code: 'custom', message: 'from is after to', path: ['from'] });
      return;
    }
    if (daysBetween(q.from, q.to) > MAX_STATS_DAYS) {
      ctx.addIssue({ code: 'custom', message: 'range too wide', path: ['to'] });
    }
  });

export type StatsQuery = z.infer<typeof statsQuery>;

